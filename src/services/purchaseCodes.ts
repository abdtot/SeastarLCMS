export function normalizePurchaseCode(code: string): string {
  return code.trim().toUpperCase().replace(/[^A-Z0-9-]/g, '');
}

export function isValidPurchaseCodeFormat(code: string): boolean {
  const norm = normalizePurchaseCode(code);
  return /^SEASTAR-[A-F0-9]{4}-[A-F0-9]{4}-[A-F0-9]{4}$/.test(norm);
}
